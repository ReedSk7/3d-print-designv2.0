import importlib.util
from pathlib import Path
import subprocess
import hashlib

ROOT=Path(__file__).parents[2]
spec=importlib.util.spec_from_file_location('output_policy',ROOT/'scripts/check_output_policy.py')
policy=importlib.util.module_from_spec(spec); spec.loader.exec_module(policy)

def test_historical_exception_requires_original_ancestry_and_exact_bytes(tmp_path,monkeypatch):
    relative='projects/agent_smoke_test_hex_bit_holder/exports/agent_smoke_test_hex_bit_holder_v01.stl'
    artifact=tmp_path/relative; artifact.parent.mkdir(parents=True); artifact.write_bytes(b'original fixture bytes')
    monkeypatch.setattr(policy,'ROOT',tmp_path)
    monkeypatch.setattr(policy,'LEGACY_ARTIFACTS',{relative:hashlib.sha256(b'original fixture bytes').hexdigest()})
    def git(*args): return subprocess.CompletedProcess(args,0,b'original fixture bytes' if args[0]=='show' else b'',b'')
    monkeypatch.setattr(policy,'run_git',git)
    assert policy.is_preserved_historical_artifact(relative)
    artifact.write_bytes(b'new generated bytes')
    assert not policy.is_preserved_historical_artifact(relative)
    monkeypatch.setattr(policy,'run_git',lambda *args:subprocess.CompletedProcess(args,1,b'',b''))
    artifact.write_bytes(b'original fixture bytes')
    assert not policy.is_preserved_historical_artifact(relative)

def test_historical_exception_cannot_allow_new_artifact(tmp_path,monkeypatch):
    monkeypatch.setattr(policy,'ROOT',tmp_path)
    assert not policy.is_preserved_historical_artifact('projects/new_part/exports/new_part.stl')

def test_original_windows_bytes_are_preserved_without_normalizing(tmp_path,monkeypatch):
    relative=next(iter(policy.LEGACY_ARTIFACTS))
    artifact=tmp_path/relative; artifact.parent.mkdir(parents=True); artifact.write_bytes(b'solid\r\nendsolid\r\n')
    monkeypatch.setattr(policy,'ROOT',tmp_path)
    monkeypatch.setattr(policy,'LEGACY_ARTIFACTS',{relative:hashlib.sha256(artifact.read_bytes()).hexdigest()})
    monkeypatch.setattr(policy,'run_git',lambda *args:subprocess.CompletedProcess(args,0,b'solid\nendsolid\n',b''))
    assert policy.is_preserved_historical_artifact(relative)
    artifact.write_bytes(b'solid\nendsolid\n')
    assert not policy.is_preserved_historical_artifact(relative)
